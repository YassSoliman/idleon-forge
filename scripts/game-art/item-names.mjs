// Writes apps/activeon/src/art/game/item-names.gen.ts: material display name ("Forest Fibres") ->
// item rawName ("Grasslands1"), from the pinned Toolbox items.json. Some views (3D Printer samples,
// Refinery fuel) only carry the display name the engine shows; this lets them draw the item's sprite.
// Only material-like kinds, so the table stays small (it rides in the lazy System pages).
// Usage: node scripts/game-art/item-names.mjs (after `pnpm --filter @idleon-forge/toolbox-parsers build`)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..');
const items = JSON.parse(
  readFileSync(join(ROOT, 'packages/toolbox-parsers/vendor/data/website-data/items.json'), 'utf8'),
);
const pin =
  /^commit=(.+)$/m.exec(readFileSync(join(ROOT, 'packages/toolbox-parsers/UPSTREAM'), 'utf8'))?.[1] ?? '';
const KINDS = new Set([
  'MONSTER_DROP',
  'LOG',
  'MATERIAL',
  'CRITTER',
  'FISH',
  'BUG',
  'ORE',
  'BAR',
  'SOUL',
  'REFINERY_SALTS',
  'WORSHIP_SKULL',
  'TRAP_BOX_SET',
]);
const out = new Map();
for (const [raw, v] of Object.entries(items)) {
  if (!KINDS.has(v.Type) || !/^[A-Za-z0-9_]+$/.test(raw)) continue;
  const name = String(v.displayName ?? '')
    .replace(/_/g, ' ')
    .trim();
  if (name && !out.has(name)) out.set(name, raw);
}
const rows = [...out.entries()]
  .sort((a, b) => a[0].localeCompare(b[0], 'en'))
  .map(([n, r]) => `  ${JSON.stringify(n)}: ${JSON.stringify(r)},`);
writeFileSync(
  join(ROOT, 'apps/activeon/src/art/game/item-names.gen.ts'),
  [
    '// SPDX-License-Identifier: GPL-3.0-only',
    '// Copyright (C) 2026 IdleOn Forge contributors.',
    `// GENERATED by scripts/game-art/item-names.mjs from Toolbox's items.json at ${pin.slice(0, 7)}. Do not edit.`,
    '// Material display name -> item rawName (its sprite is data/<rawName>).',
    'export const ITEM_BY_NAME: Readonly<Record<string, string>> = {',
    ...rows,
    '};',
    '',
  ].join('\n'),
);
console.log(`item-names.gen.ts: ${rows.length} items`);
