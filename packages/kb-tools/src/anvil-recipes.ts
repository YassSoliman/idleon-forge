// M26 F-C FR-C3a: `anvil.fact.recipes`, every recipe on anvil tabs 1-4 with its tab, its position on the
// tab (`n`, the index + 1 into `AnvilCraftStatus[tab - 1]`), its Smithing level and what unlocks it.
// Toolbox's crafts.json has no tab or position (dossier smithing M11). The IdleOn Wiki's
// `Module:Anvil/data.json` is written by its bot from the game's own files; it is cached in
// packages/knowledge/generators/_wiki-anvil.json, and the fact table in systems/anvil.facts.yaml is
// written from that cache between two marker lines. Generation itself never touches the network.
//
//   pnpm --filter @idleon-forge/kb-tools exec tsx src/anvil-recipes.ts --fetch   refresh the cache
//   pnpm --filter @idleon-forge/kb-tools exec tsx src/anvil-recipes.ts           rewrite the table
//   pnpm --filter @idleon-forge/kb-tools exec tsx src/anvil-recipes.ts --check   exit 1 if it is stale
//
// The table is tier 2 (the wiki), so it is an authored fact table with the cache's revision date as its
// claimDate; anvil-recipes.test.ts checks it against the cache and every public save's status arrays.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { KNOWLEDGE, SYSTEMS_DIR, WEBSITE_DATA } from './paths';

export const ANVIL_CACHE = path.join(KNOWLEDGE, 'generators/_wiki-anvil.json');
export const ANVIL_FACTS = path.join(SYSTEMS_DIR, 'anvil.facts.yaml');
const API = 'https://idleon.wiki/api.php';
const PAGE = 'Module:Anvil/data.json';
/** The W1-W4 tabs (Tab 5 is the W5 gate, parent N1). */
export const RECIPE_TABS = [1, 2, 3, 4] as const;
export const BEGIN = '  # BEGIN generated by kb-tools src/anvil-recipes.ts from generators/_wiki-anvil.json';
export const END = '  # END generated anvil.fact.recipes';

/** How a recipe is unlocked, as the wiki's bot data says (`others`, `monsters`). */
export type RecipeFrom = 'start' | 'quest' | 'craft' | 'drop' | 'achievement' | 'world' | 'item' | 'unknown';

export interface CachedRecipe {
  rawName: string;
  name: string;
  tab: number;
  n: number;
  lv: number;
  from: RecipeFrom;
  /** The quest, monsters, item rawName, town or achievement named by `from`. */
  by?: string;
  /** Materials: [rawName, quantity] (the wiki's costs, from the game files). */
  mats: Array<[string, number]>;
}

export interface AnvilCache {
  page: string;
  revision: number;
  /** The data page's revision date (the claimDate). */
  revised: string;
  /** The game version the bot read. */
  gameFiles: string;
  checkedOn: string;
  recipes: CachedRecipe[];
}

interface WikiRow {
  item: string;
  tab: number;
  craft: number;
  level: number;
  monsters?: { name: string }[];
  others?: string[];
  costs?: { item: string; quantity: number }[];
}

const strip = (s: string) =>
  s
    .replace(/\{\{Tooltip\|[^|]*\|\[\[([^\]|]+)(?:\|[^\]]*)?\]\][^}]*\}\}/g, '$1')
    .replace(/\{\{ItemDisplay\|([^}|]+)[^}]*\}\}/g, '$1')
    .replace(/\{\{[^}]*\}\}/g, '')
    .replace(/\[\[(?:[^\]|]*\|)?([^\]]+)\]\]/g, '$1')
    .replace(/\s+/g, ' ')
    .trim();

/** One wiki row's unlock, in the order the wiki lists them; the first one wins. */
export function fromOf(
  row: Pick<WikiRow, 'monsters' | 'others'>,
  rawOf: (name: string) => string | null,
): Pick<CachedRecipe, 'from' | 'by'> {
  const monsters = (row.monsters ?? []).map((m) => m.name).filter(Boolean);
  for (const o of row.others ?? []) {
    if (o.startsWith('Start of the tab')) return { from: 'start' };
    if (o.startsWith('Quest:')) return { from: 'quest', by: strip(o.replace(/^Quest:/, '')) };
    if (o.startsWith('Crafting')) {
      const name = strip(o.replace(/^Crafting/, ''));
      return { from: 'craft', by: rawOf(name) ?? name };
    }
    if (o.startsWith('Drop table:')) {
      // "{{Tooltip|Amarok, Baba Yaga, ...|[[DropTable1]]|...}}": the monsters, not the table's page name.
      const who =
        /\{\{Tooltip\|([^|]+)\|/
          .exec(o)?.[1]
          ?.split(',')
          .map((x) => x.trim()) ?? [];
      const shown = who.slice(0, 3).join(', ');
      return { from: 'drop', by: who.length > 3 ? `${shown} and others` : shown || strip(o) };
    }
    if (o.startsWith('Achievement:'))
      return { from: 'achievement', by: strip(o.replace(/^Achievement:/, '')) };
    if (o.startsWith('Entering')) return { from: 'world', by: strip(o.replace(/^Entering/, '')) };
    if (o.startsWith('Using')) {
      const name = strip(o.replace(/^Using/, ''));
      return { from: 'item', by: rawOf(name) ?? name };
    }
  }
  if (monsters.length) return { from: 'drop', by: monsters.join(', ') };
  return { from: 'unknown' };
}

/** Toolbox items.json display name -> rawName; a name two items share keeps the non-replica one. */
export function rawNamesByName(): (name: string) => string | null {
  const items = JSON.parse(readFileSync(path.join(WEBSITE_DATA, 'items.json'), 'utf8')) as Record<
    string,
    { displayName?: string }
  >;
  const by = new Map<string, string[]>();
  for (const [raw, it] of Object.entries(items)) {
    const name = (it.displayName ?? '').replace(/_/g, ' ').trim();
    if (!name) continue;
    by.set(name, [...(by.get(name) ?? []), raw]);
  }
  return (name: string) => {
    const all = by.get(name.trim()) ?? [];
    const real = all.filter((r) => !/Replica/.test(r));
    return (real.length === 1 ? real[0] : all.length === 1 ? all[0] : null) ?? null;
  };
}

async function fetchCache(): Promise<AnvilCache> {
  const url = `${API}?action=query&format=json&formatversion=2&prop=revisions&rvprop=content|timestamp|ids&rvslots=main&titles=${encodeURIComponent(PAGE)}`;
  const res = await fetch(url, { headers: { 'user-agent': 'idleon-forge kb-tools (anvil recipes)' } });
  if (!res.ok) throw new Error(`wiki API ${res.status}`);
  const json = (await res.json()) as {
    query?: {
      pages?: { revisions?: { revid: number; timestamp: string; slots: { main: { content: string } } }[] }[];
    };
  };
  const rev = json.query?.pages?.[0]?.revisions?.[0];
  if (!rev) throw new Error(`${PAGE}: no revision`);
  const data = JSON.parse(rev.slots.main.content) as {
    _generated?: { from?: string };
    _tables?: { tab?: { rows?: WikiRow[] } };
  };
  const rows = data._tables?.tab?.rows ?? [];
  const rawOf = rawNamesByName();
  const crafts = JSON.parse(readFileSync(path.join(WEBSITE_DATA, 'crafts.json'), 'utf8')) as Record<
    string,
    { materials?: { rawName: string; itemQuantity: number }[] }
  >;
  const recipes: CachedRecipe[] = [];
  for (const r of rows) {
    if (!(RECIPE_TABS as readonly number[]).includes(r.tab)) continue;
    const rawName = rawOf(r.item);
    if (!rawName) throw new Error(`${PAGE}: no Toolbox item named "${r.item}"`);
    // Materials from Toolbox's crafts.json (tier 1, rawNames); the wiki's costs only when it has none.
    const craft = crafts[r.item.replace(/ /g, '_')];
    const mats: Array<[string, number]> = craft?.materials?.length
      ? craft.materials.map((m) => [m.rawName, m.itemQuantity])
      : (r.costs ?? []).map((c) => {
          const raw = rawOf(c.item);
          if (!raw) throw new Error(`${PAGE}: no Toolbox item named "${c.item}" (a cost of ${r.item})`);
          return [raw, c.quantity];
        });
    recipes.push({ rawName, name: r.item, tab: r.tab, n: r.craft, lv: r.level, ...fromOf(r, rawOf), mats });
  }
  recipes.sort((a, b) => a.tab - b.tab || a.n - b.n);
  return {
    page: PAGE,
    revision: rev.revid,
    revised: rev.timestamp.slice(0, 10),
    gameFiles: data._generated?.from ?? 'unknown',
    checkedOn: new Date().toISOString().slice(0, 10),
    recipes,
  };
}

export const readCache = (): AnvilCache => JSON.parse(readFileSync(ANVIL_CACHE, 'utf8')) as AnvilCache;

const q = (s: string) => JSON.stringify(s);

/** The YAML of the `anvil.fact.recipes` table (between the markers), from the cache. */
export function tableYaml(cache: AnvilCache): string {
  const lines = [
    BEGIN,
    '  - id: anvil.fact.recipes',
    '    system: anvil',
    '    origin: authored',
    '    title: Tab, position, Smithing level and unlock of every W1-W4 anvil recipe',
    '    notes: >-',
    '      M26 FR-C3a. Written from the IdleOn Wiki bot page Module:Anvil/data.json (drawn from the game files),',
    '      cached in generators/_wiki-anvil.json. n is 1-based: AnvilCraftStatus[tab - 1][n - 1] is the',
    "      recipe's state. lv is the wiki's Smithing level, shown labelled (wiki) (V-C6, C-Q7). Superseded by",
    '      gear.fact.recipes where both name a piece (its task and merit unlocks are finer).',
    '    sources:',
    `      - { url: "https://idleon.wiki/wiki/${cache.page}", title: "IdleOn Wiki: Module:Anvil/data.json (bot-written from the game files ${cache.gameFiles}), revision ${cache.revision}", tier: 2, claimDate: ${cache.revised}, verified: ${cache.checkedOn}, gameVersion: 2.3.540 }`,
    ...RECIPE_TABS.map(
      (t) =>
        `      - { url: "https://idleon.wiki/wiki/Smithing/Anvil_Tab_${t}", title: "IdleOn Wiki: Smithing, Anvil Tab ${t}", tier: 2, claimDate: ${cache.revised}, verified: ${cache.checkedOn}, gameVersion: 2.3.540 }`,
    ),
    '    rows:',
    ...cache.recipes.map(
      (r) =>
        `      ${r.rawName}: { name: ${q(r.name)}, tab: ${r.tab}, n: ${r.n}, lv: ${r.lv}, from: ${r.from}${r.by ? `, by: ${q(r.by)}` : ''}, mats: [${r.mats.map(([m, k]) => `[${m}, ${k}]`).join(', ')}] }`,
    ),
    END,
  ];
  return `${lines.join('\n')}\n`;
}

/** The facts file with the table between its markers replaced (or appended). */
export function withTable(file: string, cache: AnvilCache): string {
  const table = tableYaml(cache);
  const a = file.indexOf(BEGIN);
  const b = file.indexOf(END);
  if (a >= 0 && b > a) return file.slice(0, a) + table + file.slice(b + END.length + 1);
  return `${file.replace(/\n*$/, '\n')}${table}`;
}

async function main() {
  const args = process.argv.slice(2);
  if (args.includes('--fetch')) {
    const cache = await fetchCache();
    writeFileSync(ANVIL_CACHE, `${JSON.stringify(cache, null, 1)}\n`);
    console.log(
      `${cache.recipes.length} recipes on tabs ${RECIPE_TABS.join(', ')} (revision ${cache.revision})`,
    );
  }
  const file = readFileSync(ANVIL_FACTS, 'utf8');
  const next = withTable(file, readCache());
  if (args.includes('--check')) {
    if (next !== file) {
      console.error('anvil.fact.recipes is stale: run src/anvil-recipes.ts');
      process.exit(1);
    }
    return;
  }
  writeFileSync(ANVIL_FACTS, next);
}

if (import.meta.url === `file://${process.argv[1]}`) await main();
